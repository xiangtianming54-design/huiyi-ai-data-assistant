CREATE TABLE IF NOT EXISTS llm_calls (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  request_id VARCHAR(64) NOT NULL,
  run_id VARCHAR(64),
  session_id VARCHAR(64),
  workspace_id BIGINT,
  user_id BIGINT,
  purpose VARCHAR(64) NOT NULL,
  provider VARCHAR(64),
  model VARCHAR(128),
  prompt_template_code VARCHAR(64),
  prompt_template_version VARCHAR(64),
  prompt_tokens INT DEFAULT 0,
  completion_tokens INT DEFAULT 0,
  total_tokens INT DEFAULT 0,
  cost_amount DECIMAL(12,6) DEFAULT 0,
  latency_ms INT,
  status VARCHAR(32) NOT NULL,
  error_message TEXT,
  created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_request_id (request_id),
  INDEX idx_run_id (run_id),
  INDEX idx_workspace_time (workspace_id, created_at),
  INDEX idx_status_time (status, created_at)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = 'LLM 调用与 Token 记录';
